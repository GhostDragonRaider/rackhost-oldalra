export function getLabModule(id: string): LabModuleMeta | undefined {
  return LAB_MODULES.find((m) => m.id === id);
}

export function listLabModulesByCategory(): Array<{
  category: LabCategoryId;
  label: string;
  modules: LabModuleMeta[];
}> {
  const order: LabCategoryId[] = [
    "overview",
    "action-center",
    "website-tools",
    "seo-lab",
    "security-center",
    "vps-monitor",
    "performance",
    "design-system",
    "calculators",
    "forms-flows",
    "client-hub",
    "leads-crm",
    "social-hub",
    "care-monitor",
    "content",
    "analytics",
    "automation",
    "ai-tools",
    "experiments",
    "testing-qa",
    "debug",
    "logs",
    "integrations",
    "settings",
  ];
  return order
    .map((category) => ({
      category,
      label: LAB_CATEGORY_LABELS[category],
      modules: LAB_MODULES.filter((m) => m.category === category),
    }))
    .filter((g) => g.modules.length > 0);
}
