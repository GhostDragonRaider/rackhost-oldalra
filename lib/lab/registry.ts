const NOW = "2026-09-27T00:00:00.000Z";

const defaultFlags = {
  enabled: false,
  public: false,
  adminOnly: true,
  beta: true,
  maintenanceMode: false,
} as const;

function mod(
  partial: Omit<LabModuleMeta, "flags" | "createdAt" | "updatedAt" | "changelog"> & {
    flags?: Partial<LabModuleMeta["flags"]>;
    changelog?: string[];
  }
): LabModuleMeta {
  return {
    ...partial,
    flags: { ...defaultFlags, ...partial.flags },
    changelog: partial.changelog || [`${partial.version} — Lab registry entry`],
    createdAt: NOW,
    updatedAt: NOW,
  };
}

